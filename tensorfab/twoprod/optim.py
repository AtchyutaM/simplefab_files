"""
CP-SAT model for the TWO-product line, with sequence-dependent changeovers.

--------------------------------------------------------------------------------
Why this is harder than the single-product model
--------------------------------------------------------------------------------
In `simplefab_1p/optim.py` a start is `x[m][t]` and the job always occupies the
tool for `pt[m]` ticks, so capacity is "at most one start per pt-tick window".

Here the duration is `setup_time[m][prev][p] + pt[m][p]` — it depends on which
product the tool last completed. That is circular: the duration depends on the
schedule, and the schedule depends on the durations.

The formulation breaks the circularity by folding the predecessor into the
decision variable:

    y[m][t][prev][p] = 1  iff machine m starts product p at tick t,
                          having last COMPLETED product `prev`

with `prev` ranging over {none, P0, P1} (index 0 = none, p+1 = product p, matching
`LineSpec2P.setup_time`'s middle axis). Duration is then a *constant* per
(m, prev, p), and both the completion tick and the changeover cost are known
without any further reasoning.

Truthfulness of `prev` is enforced by a configuration state:

    c[m][t][j] = 1  iff machine m's last completed product is j at tick t
                      (after that tick's completions, which is exactly when the
                       reference simulator reads `last_finished_product`)

    y[m][t][prev][p] <= c[m][t][prev]

--------------------------------------------------------------------------------
Timing contract, matching simplefab/sim.py
--------------------------------------------------------------------------------
* A job started at t with duration d completes at t + d. The tool is occupied for
  ticks [t, t+d-1] and is free again at t+d — a tool completing at t may start a
  new job at t.
* `last_finished_product` is read at START time, which is after that tick's
  completions. Cold start counts as a changeover (`prev != k` when prev is None),
  so the first job on a tool is charged.
* Backorder carries a one-week grace period: demand is charged only once it has
  been outstanding for `demand_interval` ticks.

--------------------------------------------------------------------------------
Model size
--------------------------------------------------------------------------------
    y : M x H x (P+1) x P   = 64,512 booleans at M=4, H=2688, P=2
    c : M x H x (P+1)       = 32,256 booleans
                              ~97k in total, against 10,752 for one product.

That ~9x growth is the point of the experiment, not an accident of the encoding:
setup structure is what scheduling MILPs are supposed to choke on. Pipeline depth
grew the single-product model linearly and CP-SAT absorbed it; this is the first
test of whether combinatorial growth breaks it.

Usage:
    from tensorfab.twoprod.optim import solve_2p
    res = solve_2p(common_cfg, time_limit_sec=600)
"""

from __future__ import annotations

import time
from typing import Any, Dict, List, Optional

import numpy as np
from ortools.sat.python import cp_model

from tensorfab.twoprod.spec import LineSpec2P, spec2p_from_common_config

# Costs are scaled to integers. 1e5 (not 1e3) so that WIP coefficients as small
# as $0.0025 keep five decimal places — the same reasoning as the single-product
# model after its COST_SCALE was raised.
COST_SCALE = 100000


def _durations(spec: LineSpec2P) -> np.ndarray:
    """dur[m, prev, p] = setup ticks + processing ticks. prev index 0 = cold."""
    return spec.setup_time + spec.pt[:, None, :]


def commander_hint(spec: LineSpec2P, common: Dict[str, Any]):
    """
    A feasible warm start, as (t, m, prev, p) tuples.

    Generated by running the reference Commander and replaying its schedule
    through the verified tensor simulator, which reports each tool's
    last-completed product at every tick. That gives `prev` exactly as the MILP
    defines it, without re-deriving it by hand.
    """
    import jax.numpy as jnp

    from simplefab.sim import ProductionLine
    from tensorfab.twoprod.tensor_sim import make_line_2p

    pt, su = common["processing_times"], common["setup_times"]
    line = ProductionLine(
        {0: pt[0][0], 1: pt[0][1]}, {0: pt[1][0], 1: pt[1][1]}, su[1],
        {0: pt[2][0], 1: pt[2][1]}, {0: pt[3][0], 1: pt[3][1]}, su[3],
        common_cfg=common,
    )
    H, M, P = spec.H, spec.n_machines, spec.n_products
    for t in range(H):
        line.run_step(current_time=t, actions_override=None)

    # Rebuild the action tape from the machines' event logs.
    tape = np.zeros((H, 1, M, P), dtype=np.int32)
    machines = [line.machine0, line.machine1, line.machine2, line.machine3]
    for m, mach in enumerate(machines):
        for e in mach.event_log:
            prod = int(e[0])
            start = int(e[1]) if m in (0, 2) else int(e[2])
            if 0 <= start < H:
                tape[start, 0, m, prod] = 1

    tl = make_line_2p(spec)
    _, tr = tl.rollout_trace(jnp.asarray(tape))
    lastp = np.asarray(tr.lastp)[:, 0]          # [H, M]

    hints = []
    for t in range(H):
        for m in range(M):
            for p in range(P):
                if tape[t, 0, m, p]:
                    hints.append((t, m, int(lastp[t, m]), p))
    return hints


def solve_2p(
    common_cfg: Dict[str, Any],
    time_limit_sec: float = 600.0,
    num_workers: int = 8,
    verbose: bool = True,
    use_hint: bool = True,
) -> Dict[str, Any]:
    spec = spec2p_from_common_config(common_cfg)
    H, M, P = spec.H, spec.n_machines, spec.n_products
    dur = _durations(spec)                       # [M, P+1, P]
    PREV = P + 1                                 # {none, P0, P1}

    t0 = time.perf_counter()
    model = cp_model.CpModel()

    # ---- decision variables ------------------------------------------------
    # y[m][t][prev][p]: start product p at t with last-completed product `prev`
    y = [[[[model.NewBoolVar(f"y{m}_{t}_{pv}_{p}") for p in range(P)]
           for pv in range(PREV)] for t in range(H)] for m in range(M)]
    # c[m][t][j]: last-completed product is j at tick t (after completions)
    c = [[[model.NewBoolVar(f"c{m}_{t}_{j}") for j in range(PREV)]
          for t in range(H)] for m in range(M)]

    # starts of product p, aggregated over the predecessor
    x = [[[sum(y[m][t][pv][p] for pv in range(PREV)) for p in range(P)]
          for t in range(H)] for m in range(M)]

    # completions: a job (m, t', prev, p) lands at t' + dur[m, prev, p]
    completes: List[List[List[Any]]] = [[[[] for _ in range(P)] for _ in range(H)]
                                        for _ in range(M)]
    for m in range(M):
        for pv in range(PREV):
            for p in range(P):
                d = int(dur[m, pv, p])
                for t in range(H - d):
                    completes[m][t + d][p].append(y[m][t][pv][p])
    comp = [[[sum(completes[m][t][p]) if completes[m][t][p] else 0
              for p in range(P)] for t in range(H)] for m in range(M)]

    # ---- capacity: at most one job occupying a tool at any tick -------------
    for m in range(M):
        occupancy: List[List[Any]] = [[] for _ in range(H)]
        for pv in range(PREV):
            for p in range(P):
                d = int(dur[m, pv, p])
                for t in range(H):
                    for u in range(t, min(H, t + d)):
                        occupancy[u].append(y[m][t][pv][p])
        for t in range(H):
            if occupancy[t]:
                model.Add(sum(occupancy[t]) <= 1)

    # ---- configuration state ------------------------------------------------
    for m in range(M):
        for t in range(H):
            model.Add(sum(c[m][t][j] for j in range(PREV)) == 1)
            any_completion = sum(comp[m][t][p] for p in range(P))
            for p in range(P):
                # a completion of p forces the state to p
                model.Add(c[m][t][p + 1] >= comp[m][t][p])
            if t == 0:
                # nothing can complete at t=0, so the tool is still cold
                model.Add(c[m][0][0] == 1)
            else:
                for j in range(PREV):
                    src = comp[m][t][j - 1] if j > 0 else 0
                    # state persists unless something else completes
                    model.Add(c[m][t][j] >= c[m][t - 1][j] - any_completion)
                    # and cannot appear from nowhere
                    model.Add(c[m][t][j] <= c[m][t - 1][j] + src)

    # ---- `prev` must match the tool's actual state --------------------------
    for m in range(M):
        for t in range(H):
            for pv in range(PREV):
                for p in range(P):
                    model.Add(y[m][t][pv][p] <= c[m][t][pv])

    # ---- queue dynamics, per product ---------------------------------------
    arr = spec.arrivals                          # [H, P]
    dem = spec.demand                            # [H, P]
    cum_dem = np.cumsum(dem, axis=0)
    max_inv = int(arr.sum() + spec.init_qfin.sum() + 16)

    q = [[[model.NewIntVar(0, max_inv, f"q{m}_{t}_{p}") for p in range(P)]
          for t in range(H)] for m in range(M)]
    qfin = [[model.NewIntVar(0, max_inv, f"qf{t}_{p}") for p in range(P)]
            for t in range(H)]
    cum_ship = [[model.NewIntVar(0, max_inv, f"cs{t}_{p}") for p in range(P)]
                for t in range(H)]
    late = [[model.NewIntVar(0, max_inv, f"late{t}_{p}") for p in range(P)]
            for t in range(H)]

    take = spec.take.astype(int)
    make = spec.make.astype(int)
    last_m = M - 1

    for t in range(H):
        for p in range(P):
            for m in range(M):
                prev_q = q[m][t - 1][p] if t > 0 else 0
                inflow = int(arr[t, p]) if m == 0 else make[m - 1] * comp[m - 1][t][p]
                model.Add(q[m][t][p] == prev_q + inflow - int(take[m]) * x[m][t][p])

            prev_fin = qfin[t - 1][p] if t > 0 else int(spec.init_qfin[p])
            prev_cs = cum_ship[t - 1][p] if t > 0 else 0
            model.Add(qfin[t][p] == prev_fin + make[last_m] * comp[last_m][t][p]
                      - cum_ship[t][p] + prev_cs)

            model.Add(cum_ship[t][p] <= int(cum_dem[t, p]))
            if t > 0:
                model.Add(cum_ship[t][p] >= cum_ship[t - 1][p])

            lag = int(spec.demand_lag_cum[t, p])
            if lag > 0:
                model.Add(late[t][p] >= lag - cum_ship[t][p])

    # ---- objective -----------------------------------------------------------
    rev_s = [int(round(spec.revenue[p] * COST_SCALE)) for p in range(P)]
    prod_s = [[int(round(spec.prod_cost[m, p] * take[m] * COST_SCALE)) for p in range(P)]
              for m in range(M)]
    setup_s = [int(round(spec.setup_cost[m] * COST_SCALE)) for m in range(M)]
    fg_s = [int(round(spec.fg_holding[p] * COST_SCALE)) for p in range(P)]
    wip_s = [[int(round(spec.wip_holding[m, p] * COST_SCALE)) for p in range(P)]
             for m in range(M)]
    bo_s = [int(round(spec.backorder[p] * COST_SCALE)) for p in range(P)]

    revenue = sum(rev_s[p] * cum_ship[H - 1][p] for p in range(P))
    production = sum(prod_s[m][p] * sum(x[m][t][p] for t in range(H))
                     for m in range(M) for p in range(P))
    # a changeover is any start whose product differs from the last completed one;
    # cold start (prev index 0) always counts
    setup = sum(setup_s[m] * y[m][t][pv][p]
                for m in range(M) if setup_s[m]
                for t in range(H) for pv in range(PREV) for p in range(P)
                if pv != p + 1)
    inventory = sum(fg_s[p] * qfin[t][p] for t in range(H) for p in range(P))
    wip = sum(wip_s[m][p] * q[m][t][p]
              for m in range(M) for p in range(P) if wip_s[m][p]
              for t in range(H))
    backorder = sum(bo_s[p] * late[t][p] for t in range(H) for p in range(P))

    model.Maximize(revenue - production - setup - inventory - wip - backorder)

    build_s = time.perf_counter() - t0
    if verbose:
        print(f"[2p-optim] model built in {build_s:.1f}s: "
              f"{M * H * PREV * P:,} y-vars, {M * H * PREV:,} c-vars")

    # ---- warm start ----------------------------------------------------------
    if use_hint:
        try:
            hints = commander_hint(spec, common_cfg)
            for (t, m, pv, p) in hints:
                model.AddHint(y[m][t][pv][p], 1)
            if verbose:
                print(f"[2p-optim] commander hint: {len(hints)} starts")
        except Exception as exc:                       # a bad hint must not block a solve
            if verbose:
                print(f"[2p-optim] hint skipped: {type(exc).__name__}: {exc}")

    # ---- solve ---------------------------------------------------------------
    solver = cp_model.CpSolver()
    solver.parameters.max_time_in_seconds = float(time_limit_sec)
    solver.parameters.num_search_workers = int(num_workers)
    solver.parameters.log_search_progress = False
    status = solver.Solve(model)
    status_name = solver.StatusName(status)

    out: Dict[str, Any] = {
        "status": status_name,
        "is_optimal": status == cp_model.OPTIMAL,
        "objective_bound": solver.BestObjectiveBound() / COST_SCALE,
        "solver_wall_time": solver.WallTime(),
        "build_seconds": build_s,
        "n_y_vars": M * H * PREV * P,
        "n_c_vars": M * H * PREV,
    }
    if status not in (cp_model.OPTIMAL, cp_model.FEASIBLE):
        out["profit"] = None
        return out

    out["profit"] = solver.ObjectiveValue() / COST_SCALE
    starts = np.zeros((H, M, P), dtype=np.int32)
    for m in range(M):
        for t in range(H):
            for pv in range(PREV):
                for p in range(P):
                    if solver.Value(y[m][t][pv][p]):
                        starts[t, m, p] = 1
    out["starts"] = starts
    out["changeovers"] = int(sum(
        solver.Value(y[m][t][pv][p])
        for m in range(M) for t in range(H)
        for pv in range(PREV) for p in range(P) if pv != p + 1))
    out["units_shipped"] = [int(solver.Value(cum_ship[H - 1][p])) for p in range(P)]
    return out
